def generate():
    for source, expected in HASHES.items():
        actual = hashlib.sha256((UPSTREAM / source).read_bytes()).hexdigest()
        if actual != expected:
            raise SystemExit(f"Source changed; review required: {source}: {actual}")
    lines = [
        "// Generated by tools/generate_bozja_skirmishes.py; edit its reviewed manifest.",
        "using System.Numerics;", "using MasterPlayer.Mechanics.Dungeons;",
        "using MasterPlayer.Spatial.Geometry;", "using MasterPlayer.Spatial.SafeZone;", "",
        "namespace MasterPlayer.Mechanics.Bozja;", "",
        "internal static class BozjaSkirmishCatalog", "{",
        "    internal static readonly BozjaDefinition[] Definitions =", "    [",
    ]
    for name, display, oid, fate, rules in MODULES:
        lines += [f'        new("{name}", "{display}", 0x{oid:X}, 0, Vector3.Zero,',
                  "            new CircleGeometry(Vector3.Zero, 30),", "        ["]
        for component, action, shape, stack in rules:
            kind = "Stack" if stack else "Aoe"
            extra = ", MinStackSize: 8" if stack else ""
            lines.append(f'            new("{component}", [{action}], BozjaRuleKind.{kind}, {shape}{extra}),')
        lines += [f"        ], FateId: {fate}),"]
    lines += ["    ];", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "Presets/Foray/Bozja/BozjaSkirmishCatalog.cs"
    expected = generate()
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8-sig") != expected:
            raise SystemExit("Generated Skirmish manifest differs")
    else:
        path.write_text(expected, encoding="utf-8", newline="\n")
    print("Verified two reviewed Skirmish sources / sixteen actual components")


if __name__ == "__main__":
    main()
