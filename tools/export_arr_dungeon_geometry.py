"""Export ARR dungeon world polygons; requires Shapely only at generation time."""
from pathlib import Path
import re
from shapely.geometry import Polygon

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "MechanicRuntime/Upstream/Modules/RealmReborn/Dungeon/D04Halatali"


def points(text, name):
    block = text.split(f" {name} = ", 1)[1].split(";", 1)[0]
    return [(float(x), float(z)) for x, z in re.findall(
        r"new\((-?[\d.]+)f?,\s*(-?[\d.]+)f?\)", block)]


def emit(name, vertices):
    # Use the bounding box center, as the upstream arena does.
    cx = (min(x for x, _ in vertices) + max(x for x, _ in vertices)) / 2
    cz = (min(z for _, z in vertices) + max(z for _, z in vertices)) / 2
    lines = [f"    internal static IGeometryShape {name}(float y) => new LocalPolygonGeometry(new({cx:.8f}f, y, {cz:.8f}f), 0, ["]
    lines.extend(f"        new({cx-x:.8f}f, {cz-z:.8f}f)," for x, z in vertices)
    return "\n".join(lines + ["    ]);"])


def main():
    fire = points((SOURCE / "D041Firemane.cs").read_text(encoding="utf-8-sig"), "vertices")
    thunder_text = (SOURCE / "D042ThunderclapGuivre.cs").read_text(encoding="utf-8-sig")
    thunder = points(thunder_text, "vertices")
    tangata = points((SOURCE / "D043Tangata.cs").read_text(encoding="utf-8-sig"), "vertices")
    shock = Polygon(thunder).difference(Polygon(points(thunder_text, "verticesAOE1"))).difference(
        Polygon(points(thunder_text, "verticesAOE2")))
    if shock.geom_type != "Polygon" or len(shock.interiors):
        raise ValueError("Shock topology changed; explicitly export and render its holes/components.")
    text = """// Generated by tools/export_arr_dungeon_geometry.py. World X/Z data from D04Halatali.
using System.Numerics;
using MasterPlayer.Spatial.Geometry;

namespace MasterPlayer.Mechanics.Dungeons;

internal static class HalataliArenas
{
"""
    text += "\n\n".join(emit(name, vertices) for name, vertices in [
        ("Firemane", fire), ("Thunderclap", thunder), ("Tangata", tangata),
        ("Shock", list(shock.exterior.coords)[:-1])])
    text += "\n}\n"
    destination = ROOT / "Presets/Dungeons/Halatali/HalataliArenas.cs"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text, encoding="utf-8", newline="\n")
    print(f"Exported 3 arenas and Shock ({len(shock.exterior.coords)-1} vertices, no interior holes).")
    haukke = SOURCE.parent / "D06Haukke"
    text = """// Generated by tools/export_arr_dungeon_geometry.py. World X/Z data from D06Haukke.
using System.Numerics;
using MasterPlayer.Spatial.Geometry;

namespace MasterPlayer.Mechanics.Dungeons;

internal static class HaukkeArenas
{
"""
    text += "\n\n".join(emit(name, points((haukke / filename).read_text(encoding="utf-8-sig"), "shape"))
        for name, filename in [("Claviger", "D061ManorClaviger.cs"), ("Steward", "D062ManorSteward.cs"),
            ("Amandine", "D063LadyAmandine.cs")])
    text += "\n}\n"
    destination = ROOT / "Presets/Dungeons/Haukke/HaukkeArenas.cs"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text, encoding="utf-8", newline="\n")
    print("Exported 3 Haukke Manor arenas.")


if __name__ == "__main__":
    main()
