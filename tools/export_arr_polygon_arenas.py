"""Export simple upstream world polygons as MP local geometry data."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "MechanicRuntime/Upstream/Modules/RealmReborn/Dungeon/D09CuttersCry"


def main():
    blocks = []
    for name, filename in [
        ("Princess", "D091MyrmidonPrincess.cs"),
        ("Worm", "D092GiantTunnelWorm.cs"),
        ("Chimera", "D093Chimera.cs"),
    ]:
        text = (SOURCE / filename).read_text(encoding="utf-8-sig")
        polygon = text.split("new PolygonCustom([", 1)[1].split("])", 1)[0]
        points = [(float(x), float(z)) for x, z in re.findall(
            r"new\((-?[\d.]+)f?,\s*(-?[\d.]+)f?\)", polygon)]
        if len(points) < 3:
            raise ValueError(f"Missing polygon: {filename}")
        cx = (min(x for x, _ in points) + max(x for x, _ in points)) / 2
        cz = (min(z for _, z in points) + max(z for _, z in points)) / 2
        lines = [f"    internal static IGeometryShape {name}(float y) => new LocalPolygonGeometry(new({cx:.8f}f, y, {cz:.8f}f), 0, ["]
        lines.extend(f"        new({cx-x:.8f}f, {cz-z:.8f}f)," for x, z in points)
        blocks.append("\n".join(lines + ["    ]);"]))
    content = """// Generated by tools/export_arr_polygon_arenas.py from D09CuttersCry world polygons.
using System.Numerics;
using MasterPlayer.Spatial.Geometry;

namespace MasterPlayer.Mechanics.Dungeons;

internal static class CuttersCryArenas
{
""" + "\n\n".join(blocks) + "\n}\n"
    destination = ROOT / "Presets/Dungeons/CuttersCry/CuttersCryArenas.cs"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(content, encoding="utf-8", newline="\n")
    print(f"Exported {len(blocks)} Cutters Cry arenas.")


if __name__ == "__main__":
    main()
