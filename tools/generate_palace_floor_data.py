"""Copy MIT floor coordinates into native MP data, without BossMod types."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "MechanicRuntime/Upstream/Modules/Global/DeepDungeon"
OUTPUT = ROOT / "Presets/PalaceOfTheDead"


def arguments(text):
    result, depth, start = [], 0, 0
    for i, char in enumerate(text):
        depth += (char == "(") - (char == ")")
        if char == "," and depth == 0:
            result.append(text[start:i].strip())
            start = i + 1
    result.append(text[start:].strip())
    return result


def generate(check=False):
    source = (SOURCE / "LoadedFloors.cs").read_text(encoding="utf-8-sig")
    lines = [
        "// Generated by tools/generate_palace_floor_data.py from MIT BMR coordinate data.",
        "using System.Numerics;", "", "namespace MasterPlayer.Mechanics.PalaceOfTheDead;", "",
        "internal static class PalaceFloorData", "{",
        "    internal static readonly Dictionary<(int FloorSet, byte Tileset), PalaceFloorRoom[]> Rooms = new()", "    {",
    ]
    room_count = 0
    for floorset in range(1, 21):
        block = source.split(f'["1.{floorset}"] = new(', 1)[1].split('["', 1)[0]
        tilesets = re.findall(r"new Tileset<Wall>\(\s*\[(.*?)\]\)", block, re.S)
        assert len(tilesets) == 2
        for tileset, text in enumerate(tilesets):
            lines += [f"        [({floorset}, {tileset})] =", "        ["]
            rows = [line.strip() for line in text.splitlines() if line.strip()]
            assert len(rows) == 25
            for row in rows:
                args = arguments(row.removeprefix("new(").removesuffix("),"))
                assert len(args) == 5
                center = args[0]
                if center != "default":
                    center = re.fullmatch(r"new\(new\((.*?)\), .*?\)", center)[1]
                    center = f"new({center})"
                lines.append(f"            new({center}, {', '.join(args[1:])}),")
                room_count += 1
            lines.append("        ],")
    lines += ["    };", "", "    internal static readonly Dictionary<ushort, Vector2[]> Traps = new()", "    {"]
    source = (SOURCE / "TrapData.cs").read_text(encoding="utf-8-sig")
    trap_counts = {}
    for territory in [*range(561, 566), *range(593, 608)]:
        body = re.search(r"\{\s*" + str(territory) + r", \[(.*?)\]\}", source, re.S)[1]
        traps = re.findall(r"new\(([^)]+)\)", body)
        trap_counts[territory] = len(traps)
        lines += [f"        [{territory}] =", "        ["]
        for i in range(0, len(traps), 4):
            lines.append("            " + ", ".join(f"new({t})" for t in traps[i:i + 4]) + ",")
        lines.append("        ],")
    lines += ["    };", "}", ""]
    assert room_count == 1000
    assert trap_counts == {
        561: 269, 562: 241, 563: 295, 564: 385, 565: 406,
        593: 423, 594: 388, 595: 391, 596: 319, 597: 330,
        598: 324, 599: 377, 600: 379, 601: 270, 602: 314,
        603: 299, 604: 269, 605: 290, 606: 278, 607: 309,
    }
    target = OUTPUT / "PalaceFloorData.cs"
    text = "\n".join(lines)
    if check:
        if target.read_text(encoding="utf-8") != text:
            raise SystemExit("PalaceFloorData.cs differs from source coordinates; regenerate it.")
    else:
        target.write_text(text, encoding="utf-8", newline="\n")
    print(f"{'Checked' if check else 'Generated'} {room_count} rooms and {sum(trap_counts.values())} trap positions.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
