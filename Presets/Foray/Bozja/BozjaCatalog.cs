    private static IGeometryShape Polygon(Vector3 center, float radius)
        => new WorldPolygonGeometry(Enumerable.Range(0, 32).Select(i =>
        {
            var angle = i * (2 * MathF.PI / 32);
            var (sin, cos) = Math.SinCos(angle);
            return center + new Vector3(radius * (float)sin, 0, radius * (float)cos);
        }), center);

    internal static bool Owns(uint territory, uint oid)
        => Definitions.Any(d => d.Territory == territory && d.PrimaryOid == oid);
